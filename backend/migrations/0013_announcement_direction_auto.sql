-- اتجاه شريط الإعلانات: 'rtl' الثابتة في البيانات القديمة كانت تفرض حركة
-- عربية حتى في الواجهة الإنجليزية (LTR) فتظهر فجوة على يمين الشاشة.
-- 'auto' = اتبع لغة الزائر الحالية (المكوّن يحوّلها إلى rtl/ltr وقت العرض).
-- المدير الذي اختار قيمة صريحة أخرى لا يتأثر إلا إن كانت القيمة القديمة
-- الافتراضية 'rtl' الموروثة من 0009/0011.
UPDATE settings
SET value = json_set(value, '$.direction', 'auto'),
    updatedAt = '2026-08-16T12:00:00Z'
WHERE key = 'announcement'
  AND json_extract(value, '$.direction') = 'rtl';
